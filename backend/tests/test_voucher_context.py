"""Template mappings, Indonesian amounts, dates and unpopulated signature blocks."""

from datetime import date
from decimal import Decimal
from pathlib import Path
from types import SimpleNamespace
import uuid

from jinja2 import Environment
from app.models.invoice_fields import HeaderFields, LineItem
from app.services.voucher_context import build_voucher_context, number


def test_indonesian_fields_and_calculated_item_total():
    req = SimpleNamespace(request_id=uuid.uuid4(), request_date=date(2026, 10, 14))
    header = HeaderFields(
        voucher_number="VCR-001",
        voucher_name="Nama pemohon",
        voucher_purpose="Biaya operasional",
        voucher_period="Oktober 2026",
        currency="IDR",
        total_amount=Decimal("25000000"),
    )
    items = [
        LineItem(
            item_date=date(2026, 10, 12), description="Barang A", quantity=10, unit_price=1000000, line_total=10000000
        ),
        LineItem(
            item_date=date(2026, 10, 14), description="Barang B", quantity=10, unit_price=1500000, line_total=15000000
        ),
    ]
    context = build_voucher_context(req, header, items, None, {}, "")
    assert context["voucher_number"] == "VCR-001"
    assert context["voucher_name"] == "Nama pemohon"
    assert context["voucher_purpose"] == "Biaya operasional"
    assert context["voucher_period"] == "Oktober 2026"
    assert context["voucher_nominal"] == "Rp 25.000.000"
    assert context["voucher_line_total"] == "25.000.000"
    assert context["line_items_table"][0]["date"] == "12/10/2026"
    html = (
        Environment(autoescape=True).from_string(Path("app/templates/voucher_default.html").read_text()).render(context)
    )
    assert "Diajukan Oleh" in html and "Disetujui Oleh" in html
    assert html.count('Nama: <span class="blank"></span>') == 2
    assert html.count('Jabatan: <span class="blank"></span>') == 2
    assert all(s not in html for s in ["AI-Prepared", "AI-Reviewed", "Generated by", "Robot Admin"])


def test_missing_purpose_and_item_date_stay_blank():
    req = SimpleNamespace(request_id=uuid.uuid4(), request_date=date(2026, 10, 14))
    header = HeaderFields(vendor_name="Vendor", invoice_date=date(2026, 10, 1), total_amount=10)
    context = build_voucher_context(req, header, [LineItem(description="Service")], None, {}, "")
    assert context["voucher_number"].startswith("VCR-20261014-")
    assert context["voucher_name"] == "Vendor"
    assert context["voucher_period"] == "01/10/2026"
    assert context["voucher_purpose"] == ""
    assert context["line_items_table"][0]["date"] == ""
    assert context["voucher_line_total"] == ""


def test_indonesian_decimals():
    assert number(Decimal("1234567.50")) == "1.234.567,50"
    assert number(0) == "0"
    assert number(None) == ""
