// Unit tests for VoucherPreview component
// Validates requirements: 14.2, 14.4
import { describe, it, expect, beforeEach, vi, afterEach } from 'vitest';
import { render, screen, waitFor, fireEvent } from '@testing-library/react';
import VoucherPreview from './VoucherPreview';

// Mock the fetch API
const createMockFetch = () => {
  const mockFetch = vi.fn();
  (globalThis as any).fetch = mockFetch;
  return mockFetch;
};

// Mock data
const mockRequestId = '123e4567-e89b-12d3-a456-426614174000';

const mockPreviewResponse = {
  request_id: mockRequestId,
  status: 'AMIGA_REVIEWED',
  authorization_disclaimer:
    'This voucher has been generated by the AMIGA Robot Admin system. ' +
    'It does not constitute independent financial approval.',
  header_fields: {
    vendor_name: 'PT Maju Bersama',
    invoice_number: 'INV-2024-001',
    invoice_date: '2024-01-15',
    currency: 'IDR',
    subtotal: '10000000.00',
    total_amount: '11100000.00',
    tax_amount: '1100000.00',
    fee_amount: '0.00',
    rounding_adj: '0.00',
  },
  line_items: [
    {
      line_item_id: 'aaa00000-0000-0000-0000-000000000001',
      sequence_number: 1,
      description: 'Consulting Services',
      quantity: '10',
      unit: 'hours',
      unit_price: '1000000.00',
      line_total: '10000000.00',
      tax_type: 'PPh 23',
      tax_rate: '2%',
      tax_amount: '200000.00',
    },
    {
      line_item_id: 'aaa00000-0000-0000-0000-000000000002',
      sequence_number: 2,
      description: 'Software License',
      quantity: '1',
      unit: 'unit',
      unit_price: '500000.00',
      line_total: '500000.00',
      // No tax fields on this item
      tax_type: null,
      tax_rate: null,
      tax_amount: null,
    },
  ],
  payment_details: {
    bank_account_number: '1234567890',
    bank_name: 'Bank Central Asia',
    payment_reference: 'PAY-REF-001',
  },
};

describe('VoucherPreview', () => {
  let mockFetch: ReturnType<typeof createMockFetch>;

  beforeEach(() => {
    vi.clearAllMocks();
    mockFetch = createMockFetch();
  });

  afterEach(() => {
    vi.clearAllMocks();
  });

  describe('Loading state', () => {
    it('shows loading indicator while fetching', async () => {
      // Keep fetch pending indefinitely so we can catch the loading state
      mockFetch.mockImplementation(
        () => new Promise(() => {}) // never resolves
      );

      render(<VoucherPreview requestId={mockRequestId} />);

      expect(screen.getByTestId('voucher-preview-loading')).toBeInTheDocument();
      expect(screen.getByText(/Loading voucher preview/i)).toBeInTheDocument();
    });
  });

  describe('Successful load', () => {
    beforeEach(() => {
      mockFetch.mockResolvedValue({
        ok: true,
        json: () => Promise.resolve(mockPreviewResponse),
      });
    });

    it('renders the voucher preview container after load', async () => {
      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-preview');
      expect(screen.getByTestId('voucher-preview')).toBeInTheDocument();
    });

    it('calls the correct voucher-preview endpoint', async () => {
      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-preview');

      expect(mockFetch).toHaveBeenCalledWith(
        `/api/requests/${mockRequestId}/voucher-preview`,
        expect.objectContaining({ headers: expect.any(Headers) })
      );
    });

    it('renders all header fields', async () => {
      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-header');

      expect(screen.getByTestId('header-vendor-name')).toHaveTextContent('PT Maju Bersama');
      expect(screen.getByTestId('header-invoice-number')).toHaveTextContent('INV-2024-001');
      expect(screen.getByTestId('header-invoice-date')).toHaveTextContent('2024-01-15');
      expect(screen.getByTestId('header-currency')).toHaveTextContent('IDR');
      expect(screen.getByTestId('header-subtotal')).toHaveTextContent('10000000.00');
      expect(screen.getByTestId('header-total-amount')).toHaveTextContent('11100000.00');
      expect(screen.getByTestId('header-tax-amount')).toHaveTextContent('1100000.00');
      expect(screen.getByTestId('header-fee-amount')).toHaveTextContent('0.00');
      expect(screen.getByTestId('header-rounding-adj')).toHaveTextContent('0.00');
    });

    it('renders line items table with correct data', async () => {
      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-line-items');

      expect(screen.getByTestId('line-item-1')).toBeInTheDocument();
      expect(screen.getByTestId('line-item-1-description')).toHaveTextContent('Consulting Services');
      expect(screen.getByTestId('line-item-2')).toBeInTheDocument();
      expect(screen.getByTestId('line-item-2-description')).toHaveTextContent('Software License');
    });

    it('renders payment details', async () => {
      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-payment-details');

      expect(screen.getByTestId('payment-bank-account-number')).toHaveTextContent('1234567890');
      expect(screen.getByTestId('payment-bank-name')).toHaveTextContent('Bank Central Asia');
      expect(screen.getByTestId('payment-reference')).toHaveTextContent('PAY-REF-001');
    });

    describe('Requirement 14.2 — Authorization Disclaimer', () => {
      it('displays the authorization disclaimer prominently', async () => {
        render(<VoucherPreview requestId={mockRequestId} />);

        const disclaimer = await screen.findByTestId('voucher-disclaimer');
        expect(disclaimer).toBeInTheDocument();

        const disclaimerText = screen.getByTestId('voucher-disclaimer-text');
        expect(disclaimerText).toHaveTextContent(mockPreviewResponse.authorization_disclaimer);
      });

      it('renders disclaimer with accessible role=note attribute', async () => {
        render(<VoucherPreview requestId={mockRequestId} />);

        await screen.findByTestId('voucher-disclaimer');

        const disclaimerSection = screen.getByRole('note', {
          name: /Authorization Disclaimer/i,
        });
        expect(disclaimerSection).toBeInTheDocument();
      });
    });

    describe('Line items — tax field presence', () => {
      it('shows tax fields for a line item that has them', async () => {
        render(<VoucherPreview requestId={mockRequestId} />);

        await screen.findByTestId('voucher-line-items');

        expect(screen.getByTestId('line-item-1-tax-type')).toHaveTextContent('PPh 23');
        expect(screen.getByTestId('line-item-1-tax-rate')).toHaveTextContent('2%');
        expect(screen.getByTestId('line-item-1-tax-amount')).toHaveTextContent('200000.00');
      });

      it('shows empty cells for tax columns when a line item has no tax', async () => {
        render(<VoucherPreview requestId={mockRequestId} />);

        await screen.findByTestId('voucher-line-items');

        expect(screen.getByTestId('line-item-2-tax-type')).toHaveTextContent('');
        expect(screen.getByTestId('line-item-2-tax-rate')).toHaveTextContent('');
        expect(screen.getByTestId('line-item-2-tax-amount')).toHaveTextContent('');
      });
    });

    it('all fields are read-only (no input elements rendered)', async () => {
      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-preview');

      const inputs = document.querySelectorAll('input, textarea, select');
      expect(inputs.length).toBe(0);
    });
  });

  describe('Requirement 14.4 — Error state and retry', () => {
    it('shows error message when the fetch fails', async () => {
      mockFetch.mockResolvedValue({
        ok: false,
        status: 500,
        statusText: 'Internal Server Error',
      });

      render(<VoucherPreview requestId={mockRequestId} />);

      const errorContainer = await screen.findByTestId('voucher-preview-error');
      expect(errorContainer).toBeInTheDocument();

      expect(screen.getByTestId('voucher-preview-error-message')).toHaveTextContent(
        /could not be generated/i
      );
    });

    it('shows a Retry button when in error state', async () => {
      mockFetch.mockResolvedValue({
        ok: false,
        status: 500,
        statusText: 'Internal Server Error',
      });

      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-preview-error');

      expect(screen.getByTestId('voucher-preview-retry')).toBeInTheDocument();
      expect(screen.getByRole('button', { name: /Retry/i })).toBeInTheDocument();
    });

    it('re-fetches when the Retry button is clicked', async () => {
      mockFetch.mockResolvedValue({
        ok: false,
        status: 500,
        statusText: 'Internal Server Error',
      });

      render(<VoucherPreview requestId={mockRequestId} />);

      await screen.findByTestId('voucher-preview-error');

      // First call during initial load
      expect(mockFetch).toHaveBeenCalledTimes(1);

      // Click retry
      fireEvent.click(screen.getByTestId('voucher-preview-retry'));

      await waitFor(() => {
        expect(mockFetch).toHaveBeenCalledTimes(2);
      });
    });

    it('recovers and shows voucher after a successful retry', async () => {
      // First call fails, second call succeeds
      mockFetch
        .mockResolvedValueOnce({ ok: false, status: 500, statusText: 'Internal Server Error' })
        .mockResolvedValueOnce({
          ok: true,
          json: () => Promise.resolve(mockPreviewResponse),
        });

      render(<VoucherPreview requestId={mockRequestId} />);

      // Wait for error state
      await screen.findByTestId('voucher-preview-error');

      // Click retry
      fireEvent.click(screen.getByTestId('voucher-preview-retry'));

      // Should now render voucher successfully
      await screen.findByTestId('voucher-preview');
      expect(screen.queryByTestId('voucher-preview-error')).not.toBeInTheDocument();
      expect(screen.getByTestId('voucher-disclaimer')).toBeInTheDocument();
    });

    it('shows error when fetch throws a network error', async () => {
      mockFetch.mockRejectedValue(new Error('Network error'));

      render(<VoucherPreview requestId={mockRequestId} />);

      const errorContainer = await screen.findByTestId('voucher-preview-error');
      expect(errorContainer).toBeInTheDocument();
      expect(screen.getByTestId('voucher-preview-error-message')).toHaveTextContent(
        /Network error/i
      );
    });
  });
});
